BEGIN;
SET LOCAL search_path TO public, pg_catalog;
-- Role Matrix roles are permission configurations, not organizational positions.
-- No role is assigned to a user by this migration.
CREATE SEQUENCE IF NOT EXISTS crm_permission_role_seq_v15;
CREATE TABLE IF NOT EXISTS crm_permission_roles (
 id uuid PRIMARY KEY,
 sequence_no bigint NOT NULL UNIQUE,
 display_id text GENERATED ALWAYS AS ('PR-'||lpad(sequence_no::text,GREATEST(3,length(sequence_no::text)),'0')) STORED UNIQUE,
 name text NOT NULL CHECK(length(name) BETWEEN 1 AND 150 AND name=btrim(name)),
 code text NOT NULL CHECK(code ~ '^[A-Z0-9][A-Z0-9-]{1,29}$'),
 department_id uuid NOT NULL REFERENCES department_units(id),
 user_type text NOT NULL CHECK(user_type IN ('Admin','Manager','Standard User')),
 description text NOT NULL DEFAULT '' CHECK(length(description)<=1000),
 status text NOT NULL DEFAULT 'Active' CHECK(status IN ('Active','Inactive')),
 permissions jsonb NOT NULL DEFAULT '{}'::jsonb CHECK(jsonb_typeof(permissions)='object'),
 fields jsonb NOT NULL DEFAULT '{}'::jsonb CHECK(jsonb_typeof(fields)='object'),
 version integer NOT NULL DEFAULT 1 CHECK(version>0),
 created_by uuid NOT NULL REFERENCES users(id),
 updated_by uuid NOT NULL REFERENCES users(id),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS crm_permission_roles_code_uq_v15 ON crm_permission_roles(upper(code));
CREATE UNIQUE INDEX IF NOT EXISTS crm_permission_roles_name_dept_tier_uq_v15 ON crm_permission_roles(department_id,user_type,lower(name));
CREATE INDEX IF NOT EXISTS crm_permission_roles_list_v15 ON crm_permission_roles(department_id,user_type,status,updated_at DESC);
CREATE TABLE IF NOT EXISTS crm_permission_role_events (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 permission_role_id uuid NOT NULL REFERENCES crm_permission_roles(id),
 actor_id uuid NOT NULL REFERENCES users(id),
 action text NOT NULL,
 changes jsonb NOT NULL DEFAULT '{}'::jsonb CHECK(jsonb_typeof(changes)='object'),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS crm_permission_role_events_lookup_v15 ON crm_permission_role_events(permission_role_id,id);
CREATE OR REPLACE TRIGGER crm_permission_role_events_append_only_v15 BEFORE UPDATE OR DELETE ON crm_permission_role_events FOR EACH ROW EXECUTE FUNCTION prevent_audit_mutation();
CREATE OR REPLACE FUNCTION validate_crm_permission_role_v15() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='INSERT' THEN
  IF NEW.sequence_no IS NOT NULL THEN RAISE EXCEPTION 'Role ID is generated by the system' USING ERRCODE='23514'; END IF;
  NEW.sequence_no:=nextval('crm_permission_role_seq_v15');
 ELSE
  IF NEW.id IS DISTINCT FROM OLD.id OR NEW.sequence_no IS DISTINCT FROM OLD.sequence_no
   OR NEW.department_id IS DISTINCT FROM OLD.department_id OR NEW.user_type IS DISTINCT FROM OLD.user_type THEN
   RAISE EXCEPTION 'Department and User Type cannot be changed; create a new role' USING ERRCODE='23514';
  END IF;
  NEW.version:=OLD.version+1;NEW.updated_at:=now();
 END IF;
 RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER validate_crm_permission_role_before_v15 BEFORE INSERT OR UPDATE ON crm_permission_roles FOR EACH ROW EXECUTE FUNCTION validate_crm_permission_role_v15();
CREATE OR REPLACE FUNCTION forbid_crm_permission_role_removal_v15() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Permission Roles must retain their history; set Inactive instead' USING ERRCODE='23514'; END $$;
CREATE OR REPLACE TRIGGER forbid_crm_permission_role_removal_before_v15 BEFORE DELETE ON crm_permission_roles FOR EACH ROW EXECUTE FUNCTION forbid_crm_permission_role_removal_v15();
DO $grants$
BEGIN
 IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='saicrm_runtime') THEN
  GRANT SELECT,INSERT,UPDATE ON crm_permission_roles TO saicrm_runtime;
  GRANT SELECT,INSERT ON crm_permission_role_events TO saicrm_runtime;
  GRANT USAGE,SELECT ON SEQUENCE crm_permission_role_seq_v15,crm_permission_role_events_id_seq TO saicrm_runtime;
 END IF;
END $grants$;
INSERT INTO schema_migrations(version) VALUES(15) ON CONFLICT DO NOTHING;
COMMIT;
