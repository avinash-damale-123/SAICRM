BEGIN;
SET LOCAL search_path TO public, pg_catalog;

-- Additive organizational positions only. Does not change users or CRM grants.
CREATE SEQUENCE IF NOT EXISTS organizational_role_display_seq_v12;
CREATE TABLE IF NOT EXISTS organizational_roles (
  id uuid PRIMARY KEY,
  sequence_no bigint NOT NULL UNIQUE,
  display_id text GENERATED ALWAYS AS ('OR-' || lpad(sequence_no::text,GREATEST(3,length(sequence_no::text)),'0')) STORED UNIQUE,
  name text NOT NULL CHECK(length(name) BETWEEN 1 AND 150 AND name=btrim(name)),
  code text NOT NULL CHECK(code ~ '^[A-Z0-9][A-Z0-9-]{1,29}$'),
  applicability text NOT NULL CHECK(applicability IN ('Central','Branch','Both')),
  family text NOT NULL DEFAULT '' CHECK(length(family)<=80),
  description text NOT NULL DEFAULT '' CHECK(length(description)<=1000),
  sort_order integer NOT NULL DEFAULT 100 CHECK(sort_order BETWEEN 1 AND 999999),
  status text NOT NULL DEFAULT 'Active' CHECK(status IN ('Active','Inactive')),
  archived_at timestamptz,
  deleted_at timestamptz,
  created_by uuid NOT NULL REFERENCES users(id),
  updated_by uuid NOT NULL REFERENCES users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  version integer NOT NULL DEFAULT 1 CHECK(version>0),
  CHECK(deleted_at IS NULL OR archived_at IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS organizational_roles_code_uq_v12 ON organizational_roles(upper(code));
CREATE UNIQUE INDEX IF NOT EXISTS organizational_roles_name_uq_v12 ON organizational_roles(lower(regexp_replace(btrim(name),'[[:space:]]+',' ','g')));
CREATE INDEX IF NOT EXISTS organizational_roles_lookup_v12 ON organizational_roles(status,applicability,updated_at DESC);
CREATE TABLE IF NOT EXISTS organizational_role_events (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  role_id uuid NOT NULL REFERENCES organizational_roles(id),
  actor_id uuid NOT NULL REFERENCES users(id),
  action text NOT NULL,
  changes jsonb NOT NULL DEFAULT '{}'::jsonb,
  reason text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS organizational_role_events_lookup_v12 ON organizational_role_events(role_id,id);
CREATE OR REPLACE TRIGGER organizational_role_events_append_only_v12
 BEFORE UPDATE OR DELETE ON organizational_role_events
 FOR EACH ROW EXECUTE FUNCTION prevent_audit_mutation();

CREATE OR REPLACE FUNCTION validate_organizational_role_v12() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='INSERT' THEN
  IF NEW.sequence_no IS NOT NULL THEN
   RAISE EXCEPTION 'Role sequence is generated by the system' USING ERRCODE='23514';
  END IF;
  NEW.sequence_no:=nextval('organizational_role_display_seq_v12');
 ELSIF TG_OP='UPDATE' THEN
  IF NEW.sequence_no IS DISTINCT FROM OLD.sequence_no OR NEW.id IS DISTINCT FROM OLD.id THEN
   RAISE EXCEPTION 'Role identity cannot be changed' USING ERRCODE='23514';
  END IF;
  NEW.updated_at:=now();
  NEW.version:=OLD.version+1;
 END IF;
 RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER validate_organizational_role_before_v12
 BEFORE INSERT OR UPDATE ON organizational_roles
 FOR EACH ROW EXECUTE FUNCTION validate_organizational_role_v12();

CREATE OR REPLACE FUNCTION block_organizational_role_removal_v12() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 RAISE EXCEPTION 'Organizational roles must retain historical records; use lifecycle states'
 USING ERRCODE='23514';
END $$;
CREATE OR REPLACE TRIGGER block_organizational_role_removal_before_v12
 BEFORE DELETE ON organizational_roles
 FOR EACH ROW EXECUTE FUNCTION block_organizational_role_removal_v12();

DO $grants$
BEGIN
 IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='saicrm_runtime') THEN
  GRANT SELECT,INSERT,UPDATE ON organizational_roles TO saicrm_runtime;
  GRANT SELECT,INSERT ON organizational_role_events TO saicrm_runtime;
  GRANT USAGE,SELECT ON SEQUENCE organizational_role_display_seq_v12,organizational_role_events_id_seq TO saicrm_runtime;
 END IF;
END $grants$;
INSERT INTO schema_migrations(version) VALUES(12) ON CONFLICT DO NOTHING;
COMMIT;
